// 2. Cost Estimation (BOQ) Generation - Optimized for Speed
export const generateBOQ = async (projectDescription) => {
    checkApiKey();
    const response = await ai.models.generateContent({
        model: "gemini-2.0-flash",
        contents: `Generate a concise Bill of Quantities (BOQ) for: "${projectDescription}". 
    Return 5-10 major line items with estimated quantities and market rates in INR.
    Use high-level estimates to be fast.`,
        config: {
            responseMimeType: "application/json",
            responseSchema: {
                type: Type.ARRAY,
                items: {
                    type: Type.OBJECT,
                    properties: {
                        item: { type: Type.STRING },
                        description: { type: Type.STRING },
                        quantity: { type: Type.NUMBER },
                        unit: { type: Type.STRING },
                        rate: { type: Type.NUMBER },
                        amount: { type: Type.NUMBER }
                    },
                    required: ["item", "description", "quantity", "unit", "rate", "amount"]
                }
            }
        }
    });
    return JSON.parse(response.text || "[]");
};
