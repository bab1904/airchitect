import { GoogleGenAI, Type } from "@google/genai";
const getApiKey = () => {
    if (typeof process !== 'undefined' && process.env) {
        if (process.env.GEMINI_API_KEY)
            return process.env.GEMINI_API_KEY;
        if (process.env.REACT_APP_GEMINI_API_KEY)
            return process.env.REACT_APP_GEMINI_API_KEY;
        if (process.env.VITE_GEMINI_API_KEY)
            return process.env.VITE_GEMINI_API_KEY;
    }
    if (typeof import.meta !== 'undefined' && import.meta?.env) {
        if (import.meta.env.VITE_GEMINI_API_KEY)
            return import.meta.env.VITE_GEMINI_API_KEY;
        if (import.meta.env.GEMINI_API_KEY)
            return import.meta.env.GEMINI_API_KEY;
    }
    return '';
};
const apiKey = getApiKey();
const ai = new GoogleGenAI({ apiKey: apiKey || 'PLACEHOLDER_KEY' });
// Helper to check key
const checkApiKey = () => {
    const key = getApiKey();
    if (!key || key === 'PLACEHOLDER_API_KEY' || key === 'PLACEHOLDER_KEY') {
        throw new Error("API Key not found or invalid. Please set your GEMINI_API_KEY or REACT_APP_GEMINI_API_KEY in environment variables.");
    }
};
// 1. Generate Floor Plan Image (2D)
export const generateFloorPlanImage = async (prompt, imageBase64) => {
    checkApiKey();
    const contents = {
        parts: []
    };
    if (imageBase64) {
        // Image-to-Image Generation (Sketch to Plan)
        const mimeType = imageBase64.substring(imageBase64.indexOf(':') + 1, imageBase64.indexOf(';'));
        const data = imageBase64.split(',')[1];
        contents.parts.push({
            inlineData: {
                mimeType: mimeType,
                data: data
            }
        });
        const textPrompt = prompt
            ? `Refine this sketch into a professional 2D CAD floor plan. Requirements: ${prompt}. Clean lines, white background.`
            : "Refine this rough sketch into a professional, clean 2D CAD floor plan. Black lines, white background.";
        contents.parts.push({ text: textPrompt });
    }
    else {
        // Text-to-Image Generation
        const systemPrompt = "Generate a professional, high-contrast 2D architectural floor plan schematic with black lines on a white background. It should look like a CAD drawing.";
        contents.parts.push({ text: `${systemPrompt} Description: ${prompt}` });
    }
    const response = await ai.models.generateContent({
        model: 'gemini-2.0-flash',
        contents: contents,
    });
    for (const part of response.candidates?.[0]?.content?.parts || []) {
        if (part.inlineData) {
            return `data:${part.inlineData.mimeType};base64,${part.inlineData.data}`;
        }
    }
    throw new Error("No image generated by the AI model. Ensure you are using a model that supports image generation.");
};
