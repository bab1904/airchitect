// 8. AI Building Code Checker - FIXED with Schema
export const runComplianceCheck = async (buildingParams) => {
    checkApiKey();
    const schema = {
        type: Type.OBJECT,
        properties: {
            overallStatus: { type: Type.STRING, enum: ["Compliant", "Non-Compliant", "Conditional Approval"] },
            score: { type: Type.NUMBER },
            checks: {
                type: Type.ARRAY,
                items: {
                    type: Type.OBJECT,
                    properties: {
                        category: { type: Type.STRING },
                        rule: { type: Type.STRING },
                        requirement: { type: Type.STRING },
                        provided: { type: Type.STRING },
                        status: { type: Type.STRING, enum: ["Pass", "Fail", "Warning"] },
                        recommendation: { type: Type.STRING }
                    },
                    required: ["category", "rule", "requirement", "provided", "status", "recommendation"]
                }
            }
        },
        required: ["overallStatus", "score", "checks"]
    };
    const response = await ai.models.generateContent({
        model: "gemini-2.0-flash",
        contents: `Check compliance for: ${JSON.stringify(buildingParams)} against NBC 2016 and AP Rules.`,
        config: {
            responseMimeType: "application/json",
            responseSchema: schema
        }
    });
    return JSON.parse(response.text || "{}");
};
